package com.networkinglab.lab2;

/**
 * Minimal JSON helper. No library is used on purpose: the lab only needs
 * to build a handful of flat JSON objects, and this makes the escaping
 * (the actual security-relevant part) explicit and inspectable.
 */
public final class JsonUtil {

    private JsonUtil() {
    }

    /** Escapes a string so it can be safely embedded inside a JSON string value. */
    public static String escape(String s) {
        if (s == null) {
            return "";
        }
        StringBuilder sb = new StringBuilder(s.length() + 8);
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"':
                    sb.append("\\\"");
                    break;
                case '\\':
                    sb.append("\\\\");
                    break;
                case '\n':
                    sb.append("\\n");
                    break;
                case '\r':
                    sb.append("\\r");
                    break;
                case '\t':
                    sb.append("\\t");
                    break;
                default:
                    if (c < 0x20) {
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
            }
        }
        return sb.toString();
    }
}
